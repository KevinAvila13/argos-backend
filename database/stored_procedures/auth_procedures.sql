-- =============================================
-- Procedure: sp_get_user_by_username
-- Description: Retrieves a user by username for authentication
--
-- What it does:
--   1. Searches for a user by username
--   2. Only returns active users
--   3. Returns all necessary fields for authentication
--
-- Parameters:
--   p_username: Username to search for
--
-- Returns: User record or empty if not found
--
-- Example usage:
--   SELECT * FROM sp_get_user_by_username('tech01');
-- =============================================
CREATE OR REPLACE FUNCTION sp_get_user_by_username(
  p_username VARCHAR(50)
)
RETURNS TABLE (
  user_id INTEGER,
  username VARCHAR(50),
  email VARCHAR(255),
  password_hash VARCHAR(255),
  full_name VARCHAR(255),
  role VARCHAR(50),
  is_active BOOLEAN,
  created_at TIMESTAMP
) AS $$
BEGIN
  RETURN QUERY
  SELECT
    u.user_id,
    u.username,
    u.email,
    u.password_hash,
    u.full_name,
    u.role,
    u.is_active,
    u.created_at
  FROM users u
  WHERE u.username = p_username;
END;
$$ LANGUAGE plpgsql;

COMMENT ON FUNCTION sp_get_user_by_username IS 'Retrieves user by username for authentication purposes.';


-- =============================================
-- Procedure: sp_get_user_by_id
-- Description: Retrieves a user by ID (for token verification)
--
-- What it does:
--   1. Searches for a user by ID
--   2. Only returns active users
--   3. Does NOT return password_hash for security
